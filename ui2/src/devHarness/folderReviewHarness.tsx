if (!import.meta.env.DEV) throw new Error('This synthetic harness is development-only.');
const params = new URLSearchParams(location.search);
document.documentElement.classList.add('dark');
// Generated by generic_folder_review_preserves_images_and_opens_real_sources.
// Paths are replaced; browser discovery/opening are simulated, never native I/O.
useFileBrowserStore.setState({
  entries: [
    {
      id: 'remote-demo',
      name: 'trillium',
      path: '/synthetic',
      type: 'directory',
      depth: 0,
      mountSource: {
        kind: 'remote',
        host: 'trillium',
        label: 'trillium',
        remotePath: '/scratch/brad/high',
      },
    },
  ],
});
let previews = 0;
setTransport({
  async invoke<T>(command: string): Promise<T> {
    if (command === 'cancel_population_sample') return undefined as T;
    if (command === 'plugin:dialog|open') return fixture.root as T;
    if (command === 'preview_folder_ontology') {
      if (params.has('slow')) await new Promise((resolve) => setTimeout(resolve, 1200));
      if (params.has('disconnected')) throw new Error('The remote source is disconnected.');
      return {
        ...fixture.ontology,
        sourceLabel: 'Synthetic remote inventory · trillium',
        truncated: params.has('truncated'),
      } as T;
    }
    if (command === 'preview_set_studio_imports') {
      previews += 1;
      const candidate = structuredClone(fixture.candidate);
      if (params.has('changed') && previews > 1) candidate.discovery.groups[0].bindings.pop();
      return [candidate] as T;
    }
    throw new Error(`Unsupported synthetic command: ${command}`);
  },
});
function Harness() {
  const open = useSetStudioStore((state) => state.importDialog.isOpen);
  const active = useSetStudioStore((state) => state.selection.activeSetId);
  return (
    <main className="grid h-screen grid-rows-[auto_minmax(0,1fr)] bg-background text-foreground">
      <p className="border-b border-border p-2 text-xs text-muted-foreground">
        Synthetic folder review · real controls, simulated discovery and opening
      </p>
      {open ? (
        <StudioFolderReview />
      ) : (
        <div className="p-6">
          <p data-testid="active-study">{active ? `Opened: ${active}` : 'No study replaced'}</p>
          <Button
            className="mt-3"
            onClick={() => void getSetIngestionService().openFolderReview(fixture.root)}
          >
            Open selected folder in Set studio…
          </Button>
        </div>
      )}
    </main>
  );
}
createRoot(document.getElementById('root')!).render(<Harness />);
