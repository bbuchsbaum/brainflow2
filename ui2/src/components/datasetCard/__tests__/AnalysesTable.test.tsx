import React from 'react';
import { fireEvent, render, screen, within } from '@testing-library/react';
import { describe, expect, it, vi } from 'vitest';
import type { DatasetAnalysis } from '@brainflow/api';
import { ANALYSIS_FILTER_FROM, AnalysesTable, ESCAPE_CLEARS_SELECTOR } from '../AnalysesTable';

function analysis(folderName: string, patch: Partial<DatasetAnalysis> = {}): DatasetAnalysis {
  return {
    path: `/d/derivatives/${folderName}`,
    folderName,
    title: null,
    generatedBy: null,
    subjectCount: 0,
    subjectCountTruncated: false,
    hasGroupLevel: false,
    hasDescription: true,
    issue: null,
    date: null,
    ...patch,
  };
}

const THREE = [
  analysis('enc_rep_rsa', {
    title: 'PCMRI — Encoding RSA',
    generatedBy: { name: 'enc_rep_rsa', version: null },
    subjectCount: 35,
  }),
  analysis('glm_recog', {
    title: 'PCMRI — Recognition GLM',
    generatedBy: { name: 'glm-recog', version: null },
    subjectCount: 0,
    hasGroupLevel: true,
  }),
  analysis('partial', {
    title: 'PCMRI — Partial',
    subjectCount: 12,
    subjectCountTruncated: true,
    issue: 'invalid JSON',
  }),
];

function many(count: number): DatasetAnalysis[] {
  return Array.from({ length: count }, (_, index) =>
    analysis(`analysis_${index + 1}`, {
      title: `Study — Model ${index + 1}`,
      subjectCount: (index * 7) % 40,
    }),
  );
}

function renderTable(
  analyses: DatasetAnalysis[],
  props: Partial<React.ComponentProps<typeof AnalysesTable>> = {},
) {
  const onOpen = vi.fn();
  render(
    <AnalysesTable
      analyses={analyses}
      label="Analyses in derivatives"
      countsPending={false}
      countsMissing={false}
      onOpen={onOpen}
      {...props}
    />,
  );
  const table = screen.getByRole('table', { name: 'Analyses in derivatives' });
  const rows = () => [...table.querySelectorAll<HTMLElement>('[data-analysis]')];
  /** The button in each row's title cell: the control that opens the analysis. */
  const openers = () => rows().map((row) => within(row).getByRole('button'));
  return {
    onOpen,
    table,
    rows,
    openers,
    names: () => rows().map((row) => row.dataset.analysis),
  };
}

/** What is on screen: the text without the parts written for a screen reader only. */
function shown(element: Element): string {
  const copy = element.cloneNode(true) as Element;
  for (const hidden of copy.querySelectorAll('.sr-only')) hidden.remove();
  return copy.textContent ?? '';
}

/** What a screen reader says: the text without the parts hidden from it. */
function spoken(element: Element): string {
  const copy = element.cloneNode(true) as Element;
  for (const hidden of copy.querySelectorAll('[aria-hidden="true"]')) hidden.remove();
  return copy.textContent ?? '';
}

/** The sort button of a column header. */
function sorter(header: HTMLElement): HTMLElement {
  return within(header).getByRole('button');
}

describe('analyses table', () => {
  it('shows a shared title prefix once and strips it from the rows', () => {
    const { rows } = renderTable(THREE);
    expect(screen.getByTestId('analysis-title-prefix')).toHaveTextContent(
      'Every title begins PCMRI —; it is left out below.',
    );
    // The full title stays in the accessible name and the tooltip: as text a
    // screen reader reads, not an `aria-label` on an element with no role.
    const title = within(rows()[0]).getByRole('button', { name: 'PCMRI — Encoding RSA' });
    expect(shown(title)).toBe('Encoding RSA');
    expect(spoken(title)).toBe('PCMRI — Encoding RSA');
    expect(title.querySelector('[aria-label]')).toBeNull();
    expect(rows()[0]).toHaveAttribute('title', 'PCMRI — Encoding RSA\nenc_rep_rsa');
    expect(shown(rows()[0])).not.toContain('PCMRI');
    // One line per analysis: a long title is cut with an ellipsis, not wrapped.
    expect(title.className).toContain('truncate');
  });

  it('has no prefix line when the titles share none', () => {
    renderTable([analysis('a', { title: 'Alpha' }), analysis('b', { title: 'Beta' })]);
    expect(screen.queryByTestId('analysis-title-prefix')).toBeNull();
  });

  it('drops "Generated by" where it repeats the folder name, and the column when it is empty', () => {
    const { table } = renderTable(THREE);
    const headers = within(table)
      .getAllByRole('columnheader')
      .map((header) => header.textContent);
    expect(headers).toEqual(['Analysis', 'Folder', 'Subjects']);
  });

  it('keeps the column for the rows that say something new, and shows a date only when declared', () => {
    const { table, rows } = renderTable([
      ...THREE,
      analysis('fmriprep', {
        title: 'PCMRI — Preprocessed',
        generatedBy: { name: 'fMRIPrep', version: '23.2.1' },
        date: '2026-03-04',
      }),
      analysis('glm2', {
        title: 'PCMRI — Second',
        generatedBy: { name: 'fmrireg', version: '0.4.1' },
      }),
    ]);
    expect(
      within(table)
        .getAllByRole('columnheader')
        .map((header) => header.textContent),
    ).toEqual(['Analysis', 'Folder', 'Generated by', 'Date', 'Subjects']);
    const cells = (row: HTMLElement) =>
      within(row)
        .getAllByRole('cell')
        .map((cell) => shown(cell));
    // enc_rep_rsa: its pipeline repeats its folder, so the cell is empty.
    expect(cells(rows()[0])[2]).toBe('');
    // A name that repeats the folder leaves its version; another name is shown whole.
    expect(cells(rows()[3]).slice(2, 4)).toEqual(['23.2.1', '2026-03-04']);
    expect(cells(rows()[4])[2]).toBe('fmrireg 0.4.1');
  });

  it('writes the subject count on one line', () => {
    const { rows } = renderTable(THREE);
    const subjects = rows().map((row) => row.querySelector('[data-subjects]') as HTMLElement);
    expect(subjects.map(shown)).toEqual(['35', 'group only', 'at least 12']);
    // Spoken in full, as text: "at least" and the unit are not lost.
    expect(subjects.map(spoken)).toEqual([
      '35 subjects',
      'Group level only, no subject folders',
      'at least 12 subjects',
    ]);
    for (const cell of subjects) expect(cell.querySelector('[aria-label]')).toBeNull();
    expect(subjects[0].className).toContain('tabular-nums');
    for (const row of rows()) expect(shown(row)).not.toMatch(/0\s*\+ group/);
    // A description that did not parse is said on the row, and in its tooltip.
    expect(within(rows()[2]).getByText('description not read in full')).toBeInTheDocument();
    expect(rows()[2].title).toContain('Description: invalid JSON');
  });

  it('opens an analysis from a click anywhere on its row, or from the button that is its title', () => {
    const { rows, openers, onOpen, table } = renderTable(THREE);
    expect(within(table).queryByRole('button', { name: /Details/ })).toBeNull();
    // One control per row, a real button (Enter and Space are its own), named
    // by the analysis. The row itself is a plain table row.
    for (const row of rows()) {
      expect(within(row).getAllByRole('button')).toHaveLength(1);
      expect(row).toHaveAttribute('role', 'row');
      expect(row).not.toHaveAttribute('tabindex');
      expect(row).not.toHaveAttribute('aria-selected');
    }
    expect(openers().map((button) => button.tagName)).toEqual(['BUTTON', 'BUTTON', 'BUTTON']);
    expect(openers()[1]).toHaveAccessibleName('PCMRI — Recognition GLM');
    fireEvent.click(rows()[0]);
    expect(onOpen).toHaveBeenLastCalledWith('/d/derivatives/enc_rep_rsa');
    // Activating the button (Enter, Space or a click) opens once, not twice.
    fireEvent.click(openers()[1]);
    expect(onOpen).toHaveBeenLastCalledWith('/d/derivatives/glm_recog');
    fireEvent.click(within(rows()[2]).getByText('description not read in full'));
    expect(onOpen).toHaveBeenLastCalledWith('/d/derivatives/partial');
    expect(onOpen).toHaveBeenCalledTimes(3);
    // A key press on the button is left to the button: nothing here swallows it.
    expect(fireEvent.keyDown(openers()[2], { key: 'Enter' })).toBe(true);
    expect(fireEvent.keyDown(openers()[2], { key: ' ' })).toBe(true);
  });

  it('is one tab stop, and arrow keys move between rows', () => {
    const { openers } = renderTable(THREE);
    expect(openers().map((button) => button.tabIndex)).toEqual([0, -1, -1]);
    openers()[0].focus();
    fireEvent.keyDown(openers()[0], { key: 'ArrowDown' });
    expect(document.activeElement).toBe(openers()[1]);
    fireEvent.keyDown(openers()[1], { key: 'End' });
    expect(document.activeElement).toBe(openers()[2]);
    fireEvent.keyDown(openers()[2], { key: 'Home' });
    expect(document.activeElement).toBe(openers()[0]);
    expect(openers().map((button) => button.tabIndex)).toEqual([0, -1, -1]);
  });

  it('is a table whose roles are valid: sort buttons inside header cells, no row count to go stale', () => {
    const { table, rows } = renderTable(many(ANALYSIS_FILTER_FROM + 1));
    expect(table).not.toHaveAttribute('aria-rowcount');
    for (const header of within(table).getAllByRole('columnheader')) {
      // A header cell is never itself the button: that would replace its role.
      expect(header.tagName).not.toBe('BUTTON');
    }
    const subjects = within(table).getByRole('columnheader', { name: /Subjects/ });
    expect(sorter(subjects)).toHaveAttribute('type', 'button');
    expect(sorter(subjects)).not.toHaveAttribute('role');
    for (const row of rows()) expect(row.querySelector('[aria-label]')).toBeNull();
  });

  it('adds the declared date to the row tooltip', () => {
    const { rows } = renderTable([
      analysis('glm', { title: 'GLM', date: '2026-03-04' }),
      analysis('rsa', { title: 'RSA' }),
    ]);
    expect(rows()[0]).toHaveAttribute('title', 'GLM\nglm\nDate: 2026-03-04');
    expect(rows()[1]).toHaveAttribute('title', 'RSA\nrsa');
  });

  it('keeps listed rows where they are when more arrive, until the user sorts', () => {
    const described = [analysis('b_glm', { title: 'GLM' }), analysis('d_rsa', { title: 'RSA' })];
    const onOpen = vi.fn();
    const props = { label: 'Analyses in derivatives', countsMissing: false, onOpen };
    const { rerender } = render(<AnalysesTable analyses={described} countsPending {...props} />);
    const table = screen.getByRole('table', { name: 'Analyses in derivatives' });
    const names = () =>
      [...table.querySelectorAll<HTMLElement>('[data-analysis]')].map((row) => row.dataset.analysis);
    expect(names()).toEqual(['b_glm', 'd_rsa']);
    const second = table.querySelector('[data-analysis="d_rsa"]') as HTMLElement;

    // The count finds folders with no description, which sort before and
    // between the listed ones. They go after: nothing listed moves.
    const counted = [
      analysis('a_prep', { hasDescription: false, subjectCount: 3 }),
      analysis('b_glm', { title: 'GLM', subjectCount: 9 }),
      analysis('c_qc', { hasDescription: false, subjectCount: 5 }),
      analysis('d_rsa', { title: 'RSA', subjectCount: 7 }),
    ];
    rerender(<AnalysesTable analyses={counted} countsPending={false} {...props} />);
    expect(names()).toEqual(['b_glm', 'd_rsa', 'a_prep', 'c_qc']);
    // The same row node, in the same place: a click in flight lands on it.
    expect(table.querySelectorAll('[data-analysis]')[1]).toBe(second);
    fireEvent.click(second);
    expect(onOpen).toHaveBeenLastCalledWith('/d/derivatives/d_rsa');

    // A sort is the user's own reordering.
    fireEvent.click(sorter(within(table).getByRole('columnheader', { name: /Analysis/ })));
    expect(names()).toEqual(['a_prep', 'c_qc', 'b_glm', 'd_rsa']);
    // A folder that is gone leaves; the others keep their order.
    rerender(
      <AnalysesTable
        analyses={counted.filter((entry) => entry.folderName !== 'b_glm')}
        countsPending={false}
        {...props}
      />,
    );
    fireEvent.click(sorter(within(table).getByRole('columnheader', { name: /Subjects/ })));
    expect(names()).toEqual(['d_rsa', 'c_qc', 'a_prep']);
  });

  it('says it is still looking when no analysis is listed yet', () => {
    const { table } = renderTable([], { countsPending: true });
    expect(within(table).getByText('Looking for analyses…')).toBeInTheDocument();
    expect(table.textContent).not.toContain('No analysis matches');
  });

  it('empties a filter on the first Escape and leaves the second to the card', () => {
    const { names } = renderTable(many(ANALYSIS_FILTER_FROM + 1));
    const filter = screen.getByRole('searchbox') as HTMLInputElement;
    // The card's host looks for this to know the press is the filter's.
    expect(filter.matches(ESCAPE_CLEARS_SELECTOR)).toBe(true);
    fireEvent.change(filter, { target: { value: 'model 12' } });
    expect(names()).toEqual(['analysis_12']);
    // Consumed: the filter is emptied.
    expect(fireEvent.keyDown(filter, { key: 'Escape' })).toBe(false);
    expect(filter.value).toBe('');
    expect(names()).toHaveLength(ANALYSIS_FILTER_FROM + 1);
    // Empty: not consumed, so it reaches the card.
    expect(fireEvent.keyDown(filter, { key: 'Escape' })).toBe(true);
  });

  it('offers a filter only for a long list', () => {
    renderTable(many(ANALYSIS_FILTER_FROM - 1));
    expect(screen.queryByRole('searchbox')).toBeNull();
  });

  it('filters by title or folder name and says how many are left', () => {
    const { names } = renderTable(many(ANALYSIS_FILTER_FROM + 1));
    const filter = screen.getByRole('searchbox', {
      name: 'Filter analyses by title or folder name',
    });
    expect(names()).toHaveLength(ANALYSIS_FILTER_FROM + 1);
    fireEvent.change(filter, { target: { value: 'model 12' } });
    expect(names()).toEqual(['analysis_12']);
    expect(screen.getByRole('status')).toHaveTextContent(`1 of ${ANALYSIS_FILTER_FROM + 1}`);
    fireEvent.change(filter, { target: { value: 'ANALYSIS_1' } });
    expect(names()).toEqual(['analysis_1', 'analysis_10', 'analysis_11', 'analysis_12']);
    fireEvent.change(filter, { target: { value: 'nothing like it' } });
    expect(names()).toEqual([]);
    expect(screen.getByText('No analysis matches “nothing like it”.')).toBeInTheDocument();
    fireEvent.change(filter, { target: { value: '' } });
    expect(names()).toHaveLength(ANALYSIS_FILTER_FROM + 1);
    expect(screen.queryByRole('status')).toBeNull();
  });

  it('sorts by name and by subjects from its headers, with aria-sort', () => {
    const { names, table } = renderTable(THREE);
    const name = within(table).getByRole('columnheader', { name: /Analysis/ });
    const subjects = within(table).getByRole('columnheader', { name: /Subjects/ });
    expect(name).toHaveAttribute('aria-sort', 'none');
    expect(names()).toEqual(['enc_rep_rsa', 'glm_recog', 'partial']);

    fireEvent.click(sorter(subjects));
    expect(subjects).toHaveAttribute('aria-sort', 'descending');
    expect(names()).toEqual(['enc_rep_rsa', 'partial', 'glm_recog']);
    fireEvent.click(sorter(subjects));
    expect(subjects).toHaveAttribute('aria-sort', 'ascending');
    expect(names()).toEqual(['glm_recog', 'partial', 'enc_rep_rsa']);

    fireEvent.click(sorter(name));
    expect(name).toHaveAttribute('aria-sort', 'ascending');
    expect(subjects).toHaveAttribute('aria-sort', 'none');
    expect(names()).toEqual(['enc_rep_rsa', 'partial', 'glm_recog']);
    fireEvent.click(sorter(name));
    expect(name).toHaveAttribute('aria-sort', 'descending');
    expect(names()).toEqual(['glm_recog', 'partial', 'enc_rep_rsa']);
  });

  it('shows quiet placeholders while the folders are counted, and does not sort by them', () => {
    const { rows, names, table } = renderTable(THREE, { countsPending: true });
    for (const row of rows()) {
      const cell = row.querySelector('[data-subjects]') as HTMLElement;
      expect(cell).toHaveAttribute('data-subjects', 'pending');
      expect(shown(cell)).toBe('…');
      // Said as text: an `aria-label` on a span with no role is not announced.
      expect(spoken(cell)).toBe('Counting');
      expect(cell.querySelector('[aria-label]')).toBeNull();
    }
    expect(table.textContent).not.toMatch(/group only|at least/);
    // Titles are already usable.
    expect(within(rows()[0]).getByText('Encoding RSA')).toBeInTheDocument();
    const subjects = within(table).getByRole('columnheader', { name: /Subjects/ });
    expect(sorter(subjects)).toHaveAttribute('aria-disabled', 'true');
    fireEvent.click(sorter(subjects));
    expect(subjects).toHaveAttribute('aria-sort', 'none');
    expect(names()).toEqual(['enc_rep_rsa', 'glm_recog', 'partial']);
    // No spinner anywhere.
    expect(table.querySelector('.animate-spin, [class*="animate-spin"]')).toBeNull();
  });

  it('says nothing rather than a wrong zero when counting failed', () => {
    const { rows } = renderTable(THREE, { countsMissing: true });
    const cell = rows()[1].querySelector('[data-subjects]') as HTMLElement;
    expect(cell).toHaveAttribute('data-subjects', 'unknown');
    expect(shown(cell)).toBe('–');
    expect(spoken(cell)).toBe('Not counted');
  });

  it('stays within the visual-style contract: tokens only, 2px radii', () => {
    const { table } = renderTable(THREE);
    const html = table.outerHTML;
    expect(html).not.toMatch(/#[0-9a-fA-F]{3,8}\b/);
    expect(html).not.toMatch(/\b(?:bg|text|border)-(?:gray|slate|zinc|neutral|red|blue|amber)-\d/);
    expect(html).not.toMatch(/rounded-(?:md|lg|xl|full)\b/);
  });
});
