// This binary triggers ts-rs type generation
use api_bridge::*;
use bridge_types::VolumeHandleInfo;
use std::path::PathBuf;
use ts_rs::TS;

/// Emit the api-bridge command list as a TypeScript constant so the frontend
/// transport surface stays derived from `api_bridge::COMMANDS` (the single source
/// of truth) instead of a hand-maintained literal.
fn export_command_list() {
    let output_dir = match std::env::var("TS_RS_EXPORT_DIR") {
        Ok(dir) => PathBuf::from(dir),
        Err(_) => {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/api/src/generated")
        }
    };

    if let Err(e) = std::fs::create_dir_all(&output_dir) {
        eprintln!(
            "Failed to create output dir for apiBridgeCommands.ts: {}",
            e
        );
        return;
    }

    let mut ts = String::new();
    ts.push_str("// Auto-generated by `cargo xtask ts-bindings` from api_bridge::COMMANDS.\n");
    ts.push_str("// DO NOT EDIT - changes will be overwritten.\n\n");
    ts.push_str("export const apiBridgeCommands = [\n");
    for cmd in COMMANDS {
        ts.push_str(&format!("  \"{}\",\n", cmd));
    }
    ts.push_str("] as const;\n\n");
    ts.push_str("export type ApiBridgeCommand = (typeof apiBridgeCommands)[number];\n");

    let path = output_dir.join("apiBridgeCommands.ts");
    match std::fs::write(&path, ts) {
        Ok(()) => println!(
            "Exported {} api-bridge command names to {}",
            COMMANDS.len(),
            path.display()
        ),
        Err(e) => eprintln!("Failed to write {}: {}", path.display(), e),
    }
}

/// Emit the module sections of the command list, joined with each module's
/// descriptor, as `BRIDGE_MODULES` (`apiBridgeModules.ts`). The UI module
/// registry reads module ids, stages and command names from here.
fn export_module_map() {
    let output_dir = match std::env::var("TS_RS_EXPORT_DIR") {
        Ok(dir) => PathBuf::from(dir),
        Err(_) => {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/api/src/generated")
        }
    };
    if let Err(e) = std::fs::create_dir_all(&output_dir) {
        eprintln!("Failed to create output dir for apiBridgeModules.ts: {}", e);
        return;
    }

    let descriptors = module_descriptors();
    let json = |value: &str| serde_json::to_string(value).expect("serialize string");

    let mut ts = String::new();
    ts.push_str("// Auto-generated by `cargo xtask ts-bindings` from the api_bridge module\n");
    ts.push_str("// descriptors and the `module <id>` sections of command_list.rs.\n");
    ts.push_str("// DO NOT EDIT - changes will be overwritten.\n\n");
    ts.push_str("import type { ModuleDescriptor } from './ModuleDescriptor';\n\n");
    ts.push_str("export const BRIDGE_MODULES = {\n");
    for (module_id, commands) in MODULE_COMMANDS {
        let descriptor = descriptors
            .iter()
            .find(|descriptor| descriptor.id == *module_id)
            .unwrap_or_else(|| panic!("module section '{module_id}' has no registered module"));
        let stage = serde_json::to_string(&descriptor.stage).expect("serialize stage");
        ts.push_str(&format!("  {module_id}: {{\n"));
        ts.push_str(&format!("    id: {},\n", json(descriptor.id)));
        ts.push_str(&format!("    title: {},\n", json(descriptor.title)));
        ts.push_str(&format!("    version: {},\n", json(descriptor.version)));
        ts.push_str(&format!("    stage: {stage},\n"));
        ts.push_str("    commands: [\n");
        for command in *commands {
            ts.push_str(&format!("      {},\n", json(command)));
        }
        ts.push_str("    ],\n");
        ts.push_str("  },\n");
    }
    ts.push_str("} as const satisfies Record<\n");
    ts.push_str("  string,\n");
    ts.push_str("  ModuleDescriptor & { readonly commands: readonly string[] }\n");
    ts.push_str(">;\n\n");
    ts.push_str("export type BridgeModuleId = keyof typeof BRIDGE_MODULES;\n");
    ts.push_str("export type BridgeModuleCommand<M extends BridgeModuleId = BridgeModuleId> =\n");
    ts.push_str("  (typeof BRIDGE_MODULES)[M]['commands'][number];\n");

    let path = output_dir.join("apiBridgeModules.ts");
    match std::fs::write(&path, ts) {
        Ok(()) => println!(
            "Exported {} api-bridge module(s) to {}",
            MODULE_COMMANDS.len(),
            path.display()
        ),
        Err(e) => eprintln!("Failed to write {}: {}", path.display(), e),
    }
}

fn main() {
    println!("Exporting TypeScript types from api_bridge...");

    export_command_list();
    export_module_map();
    ModuleInfo::export_all().expect("export module info");
    ModuleDescriptor::export_all().expect("export module descriptor");
    AtlasRoiLocation::export_all().expect("export atlas ROI locations");
    SurfaceParcelTable::export_all().expect("export surface parcel table");
    ParcelTableRequest::export_all().expect("export parcel request");
    ParcelTablePreview::export_all().expect("export parcel preview");
    ParcelOverlayInfo::export_all().expect("export parcel overlay");

    // Export all types that implement TS trait
    // Using export_all() to include dependencies

    if let Err(e) = VolumeHandleInfo::export_all() {
        eprintln!("Failed to export VolumeHandleInfo: {}", e);
    }

    if let Err(e) = TimeSeriesResult::export_all() {
        eprintln!("Failed to export TimeSeriesResult: {}", e);
    }

    if let Err(e) = VolumeBounds::export_all() {
        eprintln!("Failed to export VolumeBounds: {}", e);
    }

    if let Err(e) = LayerGpuResources::export_all() {
        eprintln!("Failed to export LayerGpuResources: {}", e);
    }

    if let Err(e) = LayerSpec::export_all() {
        eprintln!("Failed to export LayerSpec: {}", e);
    }

    if let Err(e) = VolumeLayerSpec::export_all() {
        eprintln!("Failed to export VolumeLayerSpec: {}", e);
    }

    if let Err(e) = SliceAxis::export_all() {
        eprintln!("Failed to export SliceAxis: {}", e);
    }

    if let Err(e) = SliceIndex::export_all() {
        eprintln!("Failed to export SliceIndex: {}", e);
    }

    if let Err(e) = ReleaseResult::export_all() {
        eprintln!("Failed to export ReleaseResult: {}", e);
    }

    if let Err(e) = VolumeProjectionData::export_all() {
        eprintln!("Failed to export VolumeProjectionData: {}", e);
    }

    // Phase 3 volume queries, cluster table (export_all pulls in the enums).
    ComputeClustersRequest::export_all().expect("export cluster request");
    ClusterTable::export_all().expect("export cluster table");
    VolumeExtremumRequest::export_all().expect("export extremum request");
    VoxelLocation::export_all().expect("export voxel location");
    VolumeNonzeroBboxRequest::export_all().expect("export bbox request");
    VolumeNonzeroBbox::export_all().expect("export bbox");
    RegionLocus::export_all().expect("export region locus");

    println!("TypeScript type export completed for api_bridge");
}
