// This binary triggers ts-rs type generation
use api_bridge::*;
use bridge_types::VolumeHandleInfo;
use std::path::PathBuf;
use ts_rs::TS;

/// Emit the api-bridge command list as a TypeScript constant so the frontend
/// transport surface stays derived from `api_bridge::COMMANDS` (the single source
/// of truth) instead of a hand-maintained literal.
fn export_command_list() {
    let output_dir = match std::env::var("TS_RS_EXPORT_DIR") {
        Ok(dir) => PathBuf::from(dir),
        Err(_) => {
            PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../packages/api/src/generated")
        }
    };

    if let Err(e) = std::fs::create_dir_all(&output_dir) {
        eprintln!(
            "Failed to create output dir for apiBridgeCommands.ts: {}",
            e
        );
        return;
    }

    let mut ts = String::new();
    ts.push_str("// Auto-generated by `cargo xtask ts-bindings` from api_bridge::COMMANDS.\n");
    ts.push_str("// DO NOT EDIT - changes will be overwritten.\n\n");
    ts.push_str("export const apiBridgeCommands = [\n");
    for cmd in COMMANDS {
        ts.push_str(&format!("  \"{}\",\n", cmd));
    }
    ts.push_str("] as const;\n\n");
    ts.push_str("export type ApiBridgeCommand = (typeof apiBridgeCommands)[number];\n");

    let path = output_dir.join("apiBridgeCommands.ts");
    match std::fs::write(&path, ts) {
        Ok(()) => println!(
            "Exported {} api-bridge command names to {}",
            COMMANDS.len(),
            path.display()
        ),
        Err(e) => eprintln!("Failed to write {}: {}", path.display(), e),
    }
}

fn main() {
    println!("Exporting TypeScript types from api_bridge...");

    export_command_list();
    ParcelTableRequest::export_all().expect("export parcel request");
    ParcelTablePreview::export_all().expect("export parcel preview");
    ParcelOverlayInfo::export_all().expect("export parcel overlay");

    // Export all types that implement TS trait
    // Using export_all() to include dependencies

    if let Err(e) = VolumeHandleInfo::export_all() {
        eprintln!("Failed to export VolumeHandleInfo: {}", e);
    }

    if let Err(e) = TimeSeriesResult::export_all() {
        eprintln!("Failed to export TimeSeriesResult: {}", e);
    }

    if let Err(e) = VolumeBounds::export_all() {
        eprintln!("Failed to export VolumeBounds: {}", e);
    }

    if let Err(e) = LayerGpuResources::export_all() {
        eprintln!("Failed to export LayerGpuResources: {}", e);
    }

    if let Err(e) = LayerSpec::export_all() {
        eprintln!("Failed to export LayerSpec: {}", e);
    }

    if let Err(e) = VolumeLayerSpec::export_all() {
        eprintln!("Failed to export VolumeLayerSpec: {}", e);
    }

    if let Err(e) = SliceAxis::export_all() {
        eprintln!("Failed to export SliceAxis: {}", e);
    }

    if let Err(e) = SliceIndex::export_all() {
        eprintln!("Failed to export SliceIndex: {}", e);
    }

    if let Err(e) = ReleaseResult::export_all() {
        eprintln!("Failed to export ReleaseResult: {}", e);
    }

    if let Err(e) = VolumeProjectionData::export_all() {
        eprintln!("Failed to export VolumeProjectionData: {}", e);
    }

    println!("TypeScript type export completed for api_bridge");
}
