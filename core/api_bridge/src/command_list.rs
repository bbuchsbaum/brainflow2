// This file is `include!`d from `lib.rs`, so `core` identifiers resolve in the
// crate root and each `module <id>` command resolves as `modules::<id>::<cmd>`
// (the adapter file `src/modules/<id>.rs`). It is also text-parsed by `build.rs`
// (see `command_list_parser.rs`) so the plugin permission autogeneration, including
// the per-module `module-<id>` permission sets, stays in lockstep with the runtime
// handler. The `bridge_commands!` macro expands this to `pub const COMMANDS`,
// `CORE_COMMANDS`, `MODULE_COMMANDS` and `pub fn invoke_handler`.
//
// Layout: one `core { ... }` section first, then zero or more
// `module <id> { ... }` sections, each a comma-separated list of bare snake_case
// identifiers. New module commands must be prefixed `<id>_` (the analysis
// commands are grandfathered). To add a command: add its identifier to the right
// section, grant it (`permissions/default.toml`, a capability JSON, or, for a
// module command, automatically through the module's set), then run
// `cargo xtask ts-bindings`. See `ADDING_COMMANDS.md`.
// Use only `//` line comments in this file: the text parser used by `build.rs`
// rejects anything else, including `/* */` block comments.
