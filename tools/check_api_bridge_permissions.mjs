#!/usr/bin/env node

/**
 * Single-source consistency gate for the api-bridge Tauri command surface.
 *
 * The command list has one source of truth: `core/api_bridge/src/command_list.rs`
 * (the `bridge_commands!` invocation: a `core { ... }` section, then one
 * `module <id> { ... }` section per module), which expands to `api_bridge::COMMANDS`,
 * `MODULE_COMMANDS` and the runtime invoke handler, is parsed by `build.rs` to drive
 * permission autogeneration (per command, plus one `module-<id>` set per module), and
 * is exported to `packages/api/src/generated/apiBridgeCommands.ts` and
 * `apiBridgeModules.ts` for the frontend. This script cross-checks every surface:
 *
 *   1. Every `#[command]` fn in `core/api_bridge/src/*.rs` and `src/modules/*.rs`
 *      appears in the command list (and vice versa) — i.e. the runtime handler covers
 *      exactly the defined commands.
 *   2. The generated transport list (`apiBridgeCommands.ts`) matches the command list,
 *      and `BRIDGE_MODULES` (`apiBridgeModules.ts`) matches the module sections.
 *   3. Every command has an autogenerated `permissions/autogenerated/commands/<cmd>.toml`,
 *      every module has `permissions/autogenerated/modules/<id>.toml` whose
 *      `module-<id>` set lists exactly its commands' `allow-*` ids, and nothing is stale.
 *   4. Every command is granted somewhere (`default.toml` or a capability JSON),
 *      directly or through a module set; there are no dangling `allow-*` or set
 *      grants; and `default.toml` grants module commands only through their set.
 *
 * Advisory by default (prints warnings). With `CI_STRICT_PERMISSIONS=1` it exits
 * non-zero when any inconsistency is found.
 *
 * Run: `node tools/check_api_bridge_permissions.mjs`
 *      `CI_STRICT_PERMISSIONS=1 node tools/check_api_bridge_permissions.mjs`
 */

import fs from 'node:fs/promises';
import path from 'node:path';
import url from 'node:url';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const P = {
  // Every top-level source file may define `#[command]` fns (lib.rs, analysis.rs
  // and command submodules re-exported into the crate root). bin/ and tests are
  // subdirectories and are not scanned.
  srcDir: path.join(ROOT, 'core', 'api_bridge', 'src'),
  // Module bridge adapters (`src/modules/<id>.rs`) and the module host.
  modulesSrcDir: path.join(ROOT, 'core', 'api_bridge', 'src', 'modules'),
  commandListRs: path.join(ROOT, 'core', 'api_bridge', 'src', 'command_list.rs'),
  transportTs: path.join(ROOT, 'packages', 'api', 'src', 'generated', 'apiBridgeCommands.ts'),
  modulesTs: path.join(ROOT, 'packages', 'api', 'src', 'generated', 'apiBridgeModules.ts'),
  defaultToml: path.join(ROOT, 'core', 'api_bridge', 'permissions', 'default.toml'),
  autogenCommandsDir: path.join(
    ROOT,
    'core',
    'api_bridge',
    'permissions',
    'autogenerated',
    'commands',
  ),
  autogenModulesDir: path.join(
    ROOT,
    'core',
    'api_bridge',
    'permissions',
    'autogenerated',
    'modules',
  ),
  capabilitiesDir: path.join(ROOT, 'src-tauri', 'capabilities'),
};

// Commands intentionally exempt from a specific check can be listed here.
const IGNORED_COMMANDS = new Set([]);

async function readText(filePath) {
  return fs.readFile(filePath, 'utf8');
}

/** Read every top-level `*.rs` file in `dir` (not subdirectories). */
async function rustSources(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const files = entries
    .filter((e) => e.isFile() && e.name.endsWith('.rs'))
    .map((e) => path.join(dir, e.name))
    .sort();
  return Promise.all(files.map(readText));
}

/** Scan Rust source for `#[command]` / `#[tauri::command]` functions. */
function extractCommandFns(source) {
  const lines = source.split(/\r?\n/);
  const commands = new Set();
  for (let i = 0; i < lines.length; i++) {
    const trimmed = lines[i].trim();
    if (trimmed.startsWith('//')) continue; // skip commented-out attributes
    if (!/#\[(tauri::)?command\]/.test(trimmed)) continue;
    for (let j = i + 1; j < Math.min(lines.length, i + 10); j++) {
      const line = lines[j];
      if (line.trim().startsWith('//')) continue;
      const match = line.match(/\bfn\s+([a-zA-Z0-9_]+)\s*[(<]/);
      if (match) {
        commands.add(match[1]);
        break;
      }
    }
  }
  return commands;
}

/**
 * Parse the sections of the `bridge_commands! { core { ... } module <id> { ... } }`
 * invocation. Mirrors `command_list_parser.rs`: line comments are ignored and any
 * other punctuation is an error. Returns `[{ module: null | id, commands: [...] }]`.
 */
function parseCommandSections(source) {
  const lines = source.split(/\r?\n/).map((line) => {
    const commentAt = line.indexOf('//');
    return commentAt >= 0 ? line.slice(0, commentAt) : line;
  });
  const code = lines.join('\n');
  const anchor = code.indexOf('bridge_commands!');
  if (anchor < 0) throw new Error('command_list.rs: missing `bridge_commands!` invocation');
  const tokens = [];
  for (const m of code.slice(anchor + 'bridge_commands!'.length).matchAll(/[A-Za-z0-9_]+|\S/g)) {
    if (!/^([A-Za-z0-9_]+|[{},])$/.test(m[0])) {
      throw new Error(`command_list.rs: unexpected character \`${m[0]}\``);
    }
    tokens.push(m[0]);
  }
  let i = 0;
  const next = (what) => {
    if (i >= tokens.length) throw new Error(`command_list.rs: unterminated, expected ${what}`);
    return tokens[i++];
  };
  const isIdent = (t) => /^[a-z_][a-z0-9_]*$/.test(t);
  if (next('`{`') !== '{') throw new Error('command_list.rs: expected `{` after the macro');
  const sections = [];
  for (;;) {
    const head = next('a section or `}`');
    if (head === '}') break;
    let module = null;
    if (head === 'core' && sections.length === 0) {
      module = null;
    } else if (head === 'module' && sections.length > 0) {
      module = next('a module id');
      if (!isIdent(module)) throw new Error(`command_list.rs: invalid module id \`${module}\``);
    } else {
      throw new Error(`command_list.rs: unexpected section \`${head}\``);
    }
    if (next('`{`') !== '{') throw new Error('command_list.rs: expected `{` to open a section');
    const commands = [];
    for (;;) {
      const token = next('a command or `}`');
      if (token === '}') break;
      if (!isIdent(token)) throw new Error(`command_list.rs: invalid command \`${token}\``);
      commands.push(token);
      const sep = next('`,` or `}`');
      if (sep === '}') break;
      if (sep !== ',') throw new Error(`command_list.rs: expected \`,\` after \`${token}\``);
    }
    sections.push({ module, commands });
  }
  return sections;
}

/** `module-<id>`: the permission set granting every command of a module. */
function moduleSetId(module) {
  return `module-${module.replace(/_/g, '-')}`;
}

/** Parse `[[set]]` tables (identifier + permissions) from a permission TOML. */
function parsePermissionSets(source) {
  const sets = [];
  for (const block of source.split(/^\[\[set\]\]\s*$/m).slice(1)) {
    const id = block.match(/^identifier\s*=\s*"([^"]+)"/m)?.[1];
    const list = block.match(/^permissions\s*=\s*\[([\s\S]*?)\]/m)?.[1] ?? '';
    const permissions = [...list.matchAll(/"([^"]+)"/g)].map((m) => m[1]);
    if (id) sets.push({ id, permissions });
  }
  return sets;
}

/** Parse `BRIDGE_MODULES` (module id -> command names) from `apiBridgeModules.ts`. */
function parseGeneratedModules(source) {
  const modules = new Map();
  const body = source.match(/export const BRIDGE_MODULES = \{([\s\S]*?)\n\}/)?.[1] ?? '';
  for (const m of body.matchAll(/^ {2}([a-z_][a-z0-9_]*): \{([\s\S]*?)^ {2}\},/gm)) {
    const list = m[2].match(/commands: \[([\s\S]*?)\]/)?.[1] ?? '';
    modules.set(m[1], [...list.matchAll(/"([a-z_][a-z0-9_]*)"/g)].map((c) => c[1]));
  }
  return modules;
}

/** Parse command names from the generated `apiBridgeCommands.ts`. */
function parseTransportCommands(source) {
  const names = new Set();
  const re = /"([a-z_][a-z0-9_]*)"/g;
  let m;
  while ((m = re.exec(source)) !== null) names.add(m[1]);
  return names;
}

/** `allow-get-atlas-stats` -> `get_atlas_stats`. */
function allowIdToCommand(allowId) {
  return allowId.replace(/^allow-/, '').replace(/-/g, '_');
}

function commandToAllowId(cmd) {
  return `allow-${cmd.replace(/_/g, '-')}`;
}

function extractAllowCommands(source, prefix = '') {
  const commands = new Set();
  const re = new RegExp(`"${prefix}allow-[a-z0-9-]+"`, 'g');
  let m;
  while ((m = re.exec(source)) !== null) {
    const id = m[0].slice(1, -1).slice(prefix.length);
    commands.add(allowIdToCommand(id));
  }
  return commands;
}

/** Quoted `module-*` set grants (optionally plugin-prefixed) in a grant file. */
function extractSetGrants(source, prefix = '') {
  const sets = new Set();
  const re = new RegExp(`"${prefix}(module-[a-z0-9-]+)"`, 'g');
  let m;
  while ((m = re.exec(source)) !== null) sets.add(m[1]);
  return sets;
}

async function listTomlBasenames(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  const result = new Set();
  for (const entry of entries) {
    if (entry.isFile() && entry.name.endsWith('.toml')) {
      result.add(entry.name.replace(/\.toml$/, ''));
    }
  }
  return result;
}

async function capabilityGrants() {
  const grants = new Set();
  const sets = new Set();
  const entries = await fs.readdir(P.capabilitiesDir, { withFileTypes: true });
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.json')) continue;
    const src = await readText(path.join(P.capabilitiesDir, entry.name));
    for (const cmd of extractAllowCommands(src, 'api-bridge:')) grants.add(cmd);
    for (const set of extractSetGrants(src, 'api-bridge:')) sets.add(set);
  }
  return { grants, sets };
}

/** Read every `permissions/autogenerated/modules/*.toml` -> { file, sets }. */
async function moduleSetFiles() {
  let entries = [];
  try {
    entries = await fs.readdir(P.autogenModulesDir, { withFileTypes: true });
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }
  const files = new Map();
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith('.toml')) continue;
    const src = await readText(path.join(P.autogenModulesDir, entry.name));
    files.set(entry.name.replace(/\.toml$/, ''), parsePermissionSets(src));
  }
  return files;
}

async function readOptional(filePath) {
  try {
    return await readText(filePath);
  } catch (err) {
    if (err.code === 'ENOENT') return null;
    throw err;
  }
}

function diff(a, b) {
  return [...a].filter((x) => !b.has(x)).sort();
}

async function main() {
  const [
    commandSources,
    moduleSources,
    commandListSource,
    transportSource,
    modulesTsSource,
    defaultTomlSource,
    autogenTomls,
    moduleSets,
    capabilities,
  ] = await Promise.all([
    rustSources(P.srcDir),
    rustSources(P.modulesSrcDir),
    readText(P.commandListRs),
    readText(P.transportTs),
    readOptional(P.modulesTs),
    readText(P.defaultToml),
    listTomlBasenames(P.autogenCommandsDir),
    moduleSetFiles(),
    capabilityGrants(),
  ]);

  const registeredFns = new Set(
    [...commandSources, ...moduleSources]
      .flatMap((source) => [...extractCommandFns(source)])
      .filter((c) => !IGNORED_COMMANDS.has(c)),
  );
  const sections = parseCommandSections(commandListSource);
  const commandList = new Set(sections.flatMap((s) => s.commands));
  const moduleSections = sections.filter((s) => s.module !== null);
  const transport = parseTransportCommands(transportSource);
  const generatedModules = parseGeneratedModules(modulesTsSource ?? '');

  // Known permission sets: set id -> commands it allows (from the module set files).
  const knownSets = new Map();
  for (const sets of moduleSets.values()) {
    for (const set of sets) {
      knownSets.set(
        set.id,
        new Set(set.permissions.filter((p) => p.startsWith('allow-')).map(allowIdToCommand)),
      );
    }
  }
  const expandSets = (setIds) => [...setIds].flatMap((id) => [...(knownSets.get(id) ?? [])]);

  const defaultAllow = extractAllowCommands(defaultTomlSource);
  const defaultSets = extractSetGrants(defaultTomlSource);
  const defaultGrants = new Set([...defaultAllow, ...expandSets(defaultSets)]);
  const capGrants = new Set([...capabilities.grants, ...expandSets(capabilities.sets)]);
  const allGrants = new Set([...defaultGrants, ...capGrants]);
  const directGrants = new Set([...defaultAllow, ...capabilities.grants]);

  const problems = [];
  const push = (label, items) => {
    for (const item of items) problems.push(`${label}: ${item}`);
  };

  // 1. #[command] fns vs command list (the runtime handler surface).
  push(
    '#[command] fn not in command_list.rs (defined but NOT registered in the handler)',
    diff(registeredFns, commandList),
  );
  push(
    'command_list.rs entry has no #[command] fn (registered but undefined)',
    diff(commandList, registeredFns),
  );

  // 2. Command list vs generated transport surface and module map.
  push(
    'command missing from generated apiBridgeCommands.ts (frontend calls will not be namespaced)',
    diff(commandList, transport),
  );
  push(
    'apiBridgeCommands.ts lists a non-command (stale transport entry)',
    diff(transport, commandList),
  );
  if (modulesTsSource === null && moduleSections.length > 0) {
    problems.push('missing generated apiBridgeModules.ts (run `cargo xtask ts-bindings`)');
  }
  for (const { module, commands } of moduleSections) {
    const generated = generatedModules.get(module);
    if (modulesTsSource !== null && !generated) {
      problems.push(`module missing from generated apiBridgeModules.ts: ${module}`);
    } else if (generated && generated.join(',') !== commands.join(',')) {
      problems.push(`apiBridgeModules.ts commands differ from command_list.rs: ${module}`);
    }
  }
  push(
    'apiBridgeModules.ts lists a module with no command_list.rs section (stale)',
    diff(new Set(generatedModules.keys()), new Set(moduleSections.map((s) => s.module))),
  );

  // 3. Autogenerated permission tomls: per command, and one set per module.
  push(
    'command missing permissions/autogenerated/commands/<cmd>.toml',
    diff(commandList, autogenTomls),
  );
  push(
    'stale permissions/autogenerated/commands/<cmd>.toml (no such command)',
    diff(autogenTomls, commandList),
  );
  for (const { module, commands } of moduleSections) {
    const setId = moduleSetId(module);
    const sets = moduleSets.get(module);
    const set = sets?.find((s) => s.id === setId);
    if (!set) {
      problems.push(
        `module missing permissions/autogenerated/modules/${module}.toml with set "${setId}" (run \`cargo build -p api-bridge\`)`,
      );
      continue;
    }
    const expected = commands.map(commandToAllowId);
    if (set.permissions.join(',') !== expected.join(',')) {
      problems.push(`permission set "${setId}" does not list exactly the ${module} commands`);
    }
  }
  push(
    'stale permissions/autogenerated/modules/<id>.toml (no such module)',
    diff(new Set(moduleSets.keys()), new Set(moduleSections.map((s) => s.module))),
  );

  // 4. Grants (default.toml + capability JSONs, directly or through module sets).
  push(
    'command not granted in default.toml or any capability JSON',
    diff(commandList, allGrants).map((c) => {
      const owner = moduleSections.find((s) => s.commands.includes(c));
      const grant = owner ? moduleSetId(owner.module) : commandToAllowId(c);
      return `${c} (add "${grant}")`;
    }),
  );
  push('dangling allow-* grant for a non-command', diff(directGrants, commandList));
  push(
    'dangling permission set grant (no such set)',
    diff(new Set([...defaultSets, ...capabilities.sets]), new Set(knownSets.keys())),
  );
  const moduleCommands = new Set(moduleSections.flatMap((s) => s.commands));
  push(
    'module command granted individually in default.toml (grant its module-<id> set instead)',
    [...defaultAllow].filter((c) => moduleCommands.has(c)).sort(),
  );

  const counts =
    `commands=${commandList.size} modules=${moduleSections.length} ` +
    `handlerFns=${registeredFns.size} transport=${transport.size} ` +
    `autogenTomls=${autogenTomls.size} moduleSets=${knownSets.size} ` +
    `defaultGrants=${defaultGrants.size} capabilityGrants=${capGrants.size}`;

  if (problems.length === 0) {
    console.log(`[check_api_bridge_permissions] OK: ${counts}`);
    return;
  }

  console.warn(`[check_api_bridge_permissions] Found ${problems.length} issue(s). ${counts}`);
  for (const p of problems) console.warn(` - ${p}`);

  if (process.env.CI_STRICT_PERMISSIONS === '1') {
    console.error(
      '[check_api_bridge_permissions] CI_STRICT_PERMISSIONS=1, treating issues as errors.',
    );
    process.exitCode = 1;
  }
}

main().catch((err) => {
  console.error('[check_api_bridge_permissions] Failed:', err);
  process.exitCode = 1;
});
